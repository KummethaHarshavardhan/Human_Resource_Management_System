// 3. TENURE ATTENDANCE SUMMARY STATEMENT PDF
// =============================================================================
export const createAttendanceSummaryPDF = ({
  offboarding,
  employee,
  organization,
  attendanceRecords = [],
  startDate,
  compress = false,
}) => {
  const doc = new PDFDocument({ margin: 50, size: "A4", bufferPages: true, compress });
  const marginX = 50;
  const contentWidth = doc.page.width - marginX * 2;

  const orgName = organization?.name || "Infinetra Technologies";
  const user = employee?.user_id || {};
  const empName = user.name || "Employee";
  const empCode = employee?.employee_code || "EMP";
  const designation = employee?.designation || "Employee";
  const deptName = employee?.department_id?.departmentName || user.department || "General";

  const startFormatted = formatDate(startDate || employee?.date_of_joining);
  const lwdFormatted = formatDate(offboarding?.last_working_day);
  const issueDateFormatted = formatDate(new Date());

  let y = renderLetterhead(doc, organization, "#0284C7"); // Sky/cyan theme

  doc.font("Helvetica").fontSize(9).fillColor("#64748B").text(`Date: ${issueDateFormatted}`, marginX, y, {
    width: contentWidth,
    align: "right",
  });
  y += 18;

  // Title
  doc.font("Helvetica-Bold").fontSize(15).fillColor("#0369A1").text("TENURE ATTENDANCE SUMMARY STATEMENT", marginX, y, {
    width: contentWidth,
    align: "center",
  });
  y += 20;

  // Employee Details Strip
  doc.rect(marginX, y, contentWidth, 34).fillAndStroke("#F0F9FF", "#BAE6FD");
  doc.font("Helvetica-Bold").fontSize(9.5).fillColor("#0369A1").text(`${empName} (${empCode})`, marginX + 12, y + 10);
  doc.font("Helvetica").fontSize(9).fillColor("#334155").text(`${designation} • ${deptName} • Tenure: ${startFormatted} to ${lwdFormatted}`, marginX + 180, y + 10, { width: contentWidth - 190 });
  y += 46;

  // Calculate metrics
  const totalLogs = attendanceRecords.length;
  let presentDays = 0;
  let lateDays = 0;
  let halfDays = 0;

  attendanceRecords.forEach((rec) => {
    const s = (rec.status || "").toLowerCase();
    if (s === "present") presentDays++;
    else if (s === "late") lateDays++;
    else if (s === "half day") halfDays++;
  });

  const totalEffectivePresent = presentDays + lateDays + halfDays * 0.5;
  const attendancePct = totalLogs > 0 ? ((totalEffectivePresent / totalLogs) * 100).toFixed(1) : "100.0";

  // Metrics Box
  doc.rect(marginX, y, contentWidth, 68).fillAndStroke("#F8FAFC", "#E2E8F0");
  const colW = contentWidth / 4;

  doc.font("Helvetica").fontSize(8.5).fillColor("#64748B").text("RECORDED LOGS", marginX + 10, y + 12);
  doc.font("Helvetica-Bold").fontSize(16).fillColor("#0F172A").text(`${totalLogs}`, marginX + 10, y + 26);
  doc.font("Helvetica").fontSize(8).fillColor("#94A3B8").text("Total Shift Entries", marginX + 10, y + 48);

  doc.font("Helvetica").fontSize(8.5).fillColor("#64748B").text("PRESENT DAYS", marginX + colW + 10, y + 12);
  doc.font("Helvetica-Bold").fontSize(16).fillColor("#16A34A").text(`${presentDays}`, marginX + colW + 10, y + 26);
  doc.font("Helvetica").fontSize(8).fillColor("#94A3B8").text("On-Time Full Shifts", marginX + colW + 10, y + 48);

  doc.font("Helvetica").fontSize(8.5).fillColor("#64748B").text("LATE / HALF DAYS", marginX + colW * 2 + 10, y + 12);
  doc.font("Helvetica-Bold").fontSize(16).fillColor("#D97706").text(`${lateDays + halfDays}`, marginX + colW * 2 + 10, y + 26);
  doc.font("Helvetica").fontSize(8).fillColor("#94A3B8").text(`${lateDays} Late, ${halfDays} Half`, marginX + colW * 2 + 10, y + 48);

  doc.font("Helvetica").fontSize(8.5).fillColor("#64748B").text("ATTENDANCE RATE", marginX + colW * 3 + 10, y + 12);
  doc.font("Helvetica-Bold").fontSize(16).fillColor("#0284C7").text(`${attendancePct}%`, marginX + colW * 3 + 10, y + 26);
  doc.font("Helvetica").fontSize(8).fillColor("#94A3B8").text("Effective Compliance", marginX + colW * 3 + 10, y + 48);

  y += 82;

  // Monthly Breakdown Table
  doc.font("Helvetica-Bold").fontSize(10.5).fillColor("#1E293B").text("MONTHLY ATTENDANCE AUDIT LOG:", marginX, y);
  y += 14;

  // Group by Month/Year
  const monthlyGroups = {};
  attendanceRecords.forEach((rec) => {
    const d = new Date(rec.date);
    if (isNaN(d.getTime())) return;
    const key = `${d.toLocaleString("en-IN", { month: "short" })} ${d.getFullYear()}`;
    if (!monthlyGroups[key]) {
      monthlyGroups[key] = { monthYear: key, total: 0, present: 0, late: 0, halfDay: 0 };
    }
    monthlyGroups[key].total++;
    const s = (rec.status || "").toLowerCase();
    if (s === "present") monthlyGroups[key].present++;
    else if (s === "late") monthlyGroups[key].late++;
    else if (s === "half day") monthlyGroups[key].halfDay++;
  });

  const months = Object.values(monthlyGroups).slice(0, 12); // Up to 12 months for clean layout

  // Table Header
  doc.rect(marginX, y, contentWidth, 22).fill("#0284C7");
  doc.font("Helvetica-Bold").fontSize(9).fillColor("#FFFFFF");
  doc.text("Month / Year", marginX + 10, y + 6, { width: 120 });
  doc.text("Total Logs", marginX + 140, y + 6, { width: 70, align: "center" });
  doc.text("Present", marginX + 220, y + 6, { width: 70, align: "center" });
  doc.text("Late / Half", marginX + 300, y + 6, { width: 80, align: "center" });
  doc.text("Attendance %", marginX + 390, y + 6, { width: 90, align: "center" });
  y += 22;

  if (months.length === 0) {
    doc.rect(marginX, y, contentWidth, 24).fillAndStroke("#FFFFFF", "#E2E8F0");
    doc.font("Helvetica").fontSize(9).fillColor("#64748B").text("No attendance logs recorded in this period.", marginX, y + 7, { width: contentWidth, align: "center" });
    y += 24;
  } else {
    months.forEach((m, idx) => {
      const bg = idx % 2 === 0 ? "#FFFFFF" : "#F8FAFC";
      doc.rect(marginX, y, contentWidth, 20).fillAndStroke(bg, "#E2E8F0");
      const mEffective = m.present + m.late + m.halfDay * 0.5;
      const mPct = m.total > 0 ? ((mEffective / m.total) * 100).toFixed(1) : "100.0";

      doc.font("Helvetica").fontSize(8.5).fillColor("#1E293B").text(m.monthYear, marginX + 10, y + 5);
      doc.text(String(m.total), marginX + 140, y + 5, { width: 70, align: "center" });
      doc.font("Helvetica-Bold").fillColor("#16A34A").text(String(m.present), marginX + 220, y + 5, { width: 70, align: "center" });
      doc.font("Helvetica").fillColor("#D97706").text(String(m.late + m.halfDay), marginX + 300, y + 5, { width: 80, align: "center" });
      doc.font("Helvetica-Bold").fillColor("#0284C7").text(`${mPct}%`, marginX + 390, y + 5, { width: 90, align: "center" });
      y += 20;
    });
  }

  y += 12;
  doc.font("Helvetica-Oblique").fontSize(8.5).fillColor("#64748B").text("Note: Attendance calculations represent verified electronic check-in logs during employment.", marginX, y);

  renderFooter(doc, "Attendance & Operations Department", orgName);
  return doc;
};

