import PDFDocument from "pdfkit";

/**
 * Format a Date object to "DD Month YYYY"
 */
export const formatDate = (date) => {
  if (!date) return "—";
  const d = new Date(date);
  if (isNaN(d.getTime())) return "—";
  return d.toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "long",
    year: "numeric",
  });
};

/**
 * Helper to render standard company letterhead
 */
const renderLetterhead = (doc, organization, primaryColor = "#6C5CE7") => {
  const pageWidth = doc.page.width;
  const marginX = 50;
  const contentWidth = pageWidth - marginX * 2;

  const orgName = organization?.name || "The Organization";
  const orgAddress = organization?.address || "";
  const orgEmail = organization?.contactEmail || "";
  const orgPhone = organization?.contactPhone || "";

  // Top accent bar
  doc.rect(0, 0, pageWidth, 8).fill(primaryColor);

  let y = 35;
  doc
    .font("Helvetica-Bold")
    .fontSize(18)
    .fillColor("#1E293B")
    .text(orgName.toUpperCase(), marginX, y, { width: contentWidth, align: "left" });

  y += 24;

  const contactParts = [];
  if (orgAddress) contactParts.push(orgAddress);
  if (orgEmail) contactParts.push(`Email: ${orgEmail}`);
  if (orgPhone) contactParts.push(`Phone: ${orgPhone}`);

  if (contactParts.length > 0) {
    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor("#64748B")
      .text(contactParts.join("  |  "), marginX, y, {
        width: contentWidth,
        align: "left",
      });
    y += 18;
  }

  // Divider
  doc
    .moveTo(marginX, y)
    .lineTo(pageWidth - marginX, y)
    .strokeColor("#E2E8F0")
    .lineWidth(1)
    .stroke();

  return y + 16;
};

/**
 * Helper to render standard document footer
 */
const renderFooter = (doc, signatoryTitle = "Human Resources Department", orgName = "The Organization") => {
  const pageWidth = doc.page.width;
  const marginX = 50;
  const contentWidth = pageWidth - marginX * 2;

  let y = doc.y + 24;
  if (y > 680) {
    doc.addPage();
    y = 50;
  }

  doc.font("Helvetica").fontSize(10).fillColor("#1F2937");
  doc.text("Sincerely,", marginX, y);
  y += 14;

  doc.font("Helvetica-Bold").fontSize(10).fillColor("#1E293B");
  doc.text(`For ${orgName}`, marginX, y);
  y += 36;

  // Signature line
  doc
    .moveTo(marginX, y)
    .lineTo(marginX + 170, y)
    .strokeColor("#94A3B8")
    .lineWidth(1)
    .stroke();

  y += 6;
  doc.font("Helvetica-Bold").fontSize(10).fillColor("#1E293B");
  doc.text("Authorized Signatory", marginX, y);
  y += 14;

  doc.font("Helvetica").fontSize(9).fillColor("#64748B");
  doc.text(signatoryTitle, marginX, y);

  // Bottom confidentiality note
  const bottomY = doc.page.height - 35;
  doc
    .font("Helvetica-Oblique")
    .fontSize(8)
    .fillColor("#94A3B8")
    .text(
      "This is an official document generated by the Human Resource Management System.",
      marginX,
      bottomY,
      { width: contentWidth, align: "center" }
    );
};

